# ============================================================
# БЛОК 1. ИМПОРТЫ
# ============================================================
# Импорт — это подключение «чужого» кода (библиотеки) в наш файл,
# чтобы пользоваться готовыми функциями, а не писать всё с нуля.

# requests — библиотека для отправки HTTP-запросов (аналог браузера).
import requests

# BeautifulSoup — класс из библиотеки bs4 для разбора HTML.
# Извлекаем его из модуля, чтобы писать короче: BeautifulSoup(...), а не bs4.BeautifulSoup(...).
from bs4 import BeautifulSoup

# pandas — библиотека для таблиц. Сокращаем имя до pd (общепринятое соглашение).
import pandas as pd


# ============================================================
# БЛОК 2. ФОРМИРОВАНИЕ URL
# ============================================================
# URL (Uniform Resource Locator) — адрес страницы в интернете.

# Записываем название предмета. Оно должно ТОЧНО совпадать с тем,
# как Steam его отображает, иначе страница не найдётся.
item_name = "AK-47 | Neon Revolution (Field-Tested)"

# В URL нельзя использовать пробелы и некоторые символы.
# Их нужно заменить на «процентное кодирование» (percent-encoding):
#   пробел -> %20
#   символ | -> %7C
# Это требование стандарта URL (RFC 3986).
encoded_name = item_name.replace(" ", "%20").replace("|", "%7C")

# f-строка (f"") — это строка с подстановкой переменных в {фигурных скобках}.
# Формируем адрес страницы: /market/listings/{ID_игры}/{название}.
# 730 — это AppID игры Counter-Strike 2 (раньше CS:GO).
url = f"https://steamcommunity.com/market/listings/730/{encoded_name}"


# ============================================================
# БЛОК 3. HTTP-ЗАПРОС
# ============================================================
# Отправляем GET-запрос к серверу Steam.
# GET — это метод HTTP, означающий «дай мне данные» (в отличие от POST, который «отправь данные»).
# Сервер вернёт объект Response, в котором лежат: статус, заголовки, HTML и т.д.
response = requests.get(url)


# ============================================================
# БЛОК 4. ПРОВЕРКА ОТВЕТА
# ============================================================
# status_code — числовой код состояния HTTP (200, 404, 403...).
# Если он не 200, дальше идти нет смысла — данных мы не получим.
if response.status_code != 200:
    # f-строка для вывода кода ошибки.
    print(f"Ошибка при запросе: {response.status_code}")
    # exit() — аварийное завершение программы.
    exit()


# ============================================================
# БЛОК 5. СОЗДАНИЕ «СУПА» (PARSER)
# ============================================================
# BeautifulSoup превращает сырой HTML-текст (response.text)
# в объект-дерево, по которому удобно искать элементы.
# Второй аргумент "html.parser" — это движок разбора, встроенный в Python.
soup = BeautifulSoup(response.text, "html.parser")


# ============================================================
# БЛОК 6. ПОИСК ЛОТОВ
# ============================================================
# find_all — метод, который находит ВСЕ элементы, подходящие под условие.
# "div" — тег, который мы ищем.
# class_="market_listing_row" — атрибут class со значением market_listing_row.
#   (class_ с подчёркиванием, потому что слово class зарезервировано в Python.)
# Результат — список (list) объектов Tag (это те самые <div> ... </div>).
items = soup.find_all("div", class_="market_listing_row")


# ============================================================
# БЛОК 7. СБОР ДАННЫХ
# ============================================================
# Список data — «корзина», куда будем складывать словари с информацией.
# Словарь (dict) — структура вида {"ключ": "значение"}.
data = []

# Цикл for перебирает элементы списка items один за другим.
# На каждой итерации переменная item = очередной лот (объект Tag).
for item in items:

    # Ищем внутри лота <span> с классом "market_listing_price_with_fee".
    # Это цена, которую заплатит покупатель (включая комиссию Steam 15%).
    # find вернёт либо объект Tag, либо None, если ничего не найдено.
    price_span = item.find("span", class_="market_listing_price_with_fee")

    # Проверяем: если элемент найден (не None), то идём дальше.
    # Это защита от ошибки AttributeError, если span окажется пустым.
    if price_span:
        # .text — атрибут, который возвращает ВЕСЬ текст внутри тега (с пробелами и переводами строк).
        # .strip() — метод строки, удаляющий пробелы и переносы с начала и с конца.
        price = price_span.text.strip()

        # Ищем название предмета в лоте.
        name_span = item.find("span", class_="market_listing_item_name")

        # Тернарный оператор (сокращённый if-else):
        # "X if условие else Y" — вернёт X, если условие True, и Y, если False.
        # Здесь: если name_span найден, берём его текст, иначе — используем общее название.
        name = name_span.text.strip() if name_span else item_name

        # Добавляем в список data словарь с двумя ключами.
        # list.append() — метод списка, добавляющий элемент в конец.
        data.append({"Название": name, "Цена": price})


# ============================================================
# БЛОК 8. СОЗДАНИЕ ТАБЛИЦЫ
# ============================================================
# pd.DataFrame — конструктор таблицы.
# Из списка словарей [{"Название":..., "Цена":...}, ...] он автоматически
# сделает таблицу: ключи станут столбцами, значения — строками.
df = pd.DataFrame(data)


# ============================================================
# БЛОК 9. СОХРАНЕНИЕ В EXCEL
# ============================================================
# to_excel — метод DataFrame, сохраняющий таблицу в файл .xlsx.
# Первый аргумент — имя файла.
# index=False — не записывать в Excel столбец с индексами строк (0, 1, 2...).
df.to_excel("result.xlsx", index=False)


# ============================================================
# БЛОК 10. ОТЧЁТ
# ============================================================
# len(data) — длина списка, т.е. количество найденных лотов.
print(f"Готово! Файл result.xlsx создан. Найдено лотов: {len(data)}")


# ============================================================
# БЛОК 11. ПРОВЕРКА ФАЙЛА
# ============================================================
# os — модуль для работы с операционной системой (файлы, папки, пути).
import os

# os.getcwd() — «get current working directory», текущая рабочая папка.
print("Текущая папка:", os.getcwd())

# os.path.exists — проверяет, существует ли файл/папка по указанному пути.
# Возвращает True или False.
print("Файл существует:", os.path.exists("result.xlsx"))

# Если файл есть — показываем его полный (абсолютный) путь.
# os.path.abspath — превращает относительный путь в абсолютный.
if os.path.exists("result.xlsx"):
    print("Полный путь:", os.path.abspath("result.xlsx"))